pairs_map = {
    ")": "(",
    "]": "[",
    "}": "{",
    ">": "<"
}

open_to_close_map = {
    "(": ")",
    "[": "]",
    "{": "}",
    "<": ">"
}

corrupted_points_map = {
    ")": 3,
    "]": 57,
    "}": 1197,
    ">": 25137
}

corrupted_count = {
    ")": 0, # 2
    "]": 0, # 1
    "}": 0, # 1
    ">": 0 # 1
}

incomplete_points_map = {
    ")": 1,
    "]": 2,
    "}": 3,
    ">": 4
}

multiplier = 5
completion_scores = []

# <{([([[(<>()){}]>(<<{{
for line in navigation_subsystem:
    stack = [] # < { ( [ ( [

    for char in line:
        if char not in pairs_map:
            stack.append(char)
            continue
            
        if not stack or pairs_map[char] != stack[-1]:
            corrupted_count[char] += 1
            stack = []
            break

        stack.pop()
    
    if stack:
        score = 0
        for char in stack[::-1]:
            score *= multiplier
            score += incomplete_points_map[open_to_close_map[char]]

        completion_scores.append(score)

# PART 1:
corrupted_score = 0
for char, count in corrupted_count.items():
    corrupted_score += count * corrupted_points_map[char]
print("CORRUPTED SCORE: ", corrupted_score)

# PART 2:
completion_scores.sort()
n = len(completion_scores)
middle_completion_score = completion_scores[n // 2]
print("COMPLETION SCORE: ", middle_completion_score)

